export const SchedulerJobSchema = {
  collection: 'schedulerJobs',
  fields: {
    jobId: 'string',
    version: 'string',
    owner: 'string',
    tenantId: 'string?',
    environment: 'string',
    scope: {
      tenantId: 'string?',
      branchId: 'string?',
    },
    requestId: 'string',
    correlationId: 'string',
    idempotencyKey: 'string',
    queueName: 'string',
    status: [
      'Pending',
      'Waiting',
      'Delayed',
      'Active',
      'Completed',
      'Failed',
      'RetryScheduled',
      'DeadLettered',
      'Cancelled',
      'Expired',
    ],
    attempts: 'number',
    maxAttempts: 'number',
    payloadReference: 'string',
    payloadChecksum: 'string',
    priority: 'number',
    delayMs: 'number',
    metadata: 'metadata',
    failureReason: 'string?',
    deadLetterReason: 'string?',
    replayCount: 'number',
    scheduledAtUtc: 'utc-iso',
    createdAtUtc: 'utc-iso',
    updatedAtUtc: 'utc-iso',
  },
  indexes: [
    { jobId: 1, unique: true },
    { owner: 1, idempotencyKey: 1 },
    { tenantId: 1, status: 1 },
    { requestId: 1 },
    { correlationId: 1 },
    { createdAtUtc: -1 },
    { scheduledAtUtc: -1 },
  ],
} as const;

